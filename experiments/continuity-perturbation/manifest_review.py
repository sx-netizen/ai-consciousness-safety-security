#!/usr/bin/env python3
"""Offline, human-readable CPB v0.4 manifest review. No provider calls."""
from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path

import runner

BASE = Path(__file__).resolve().parent

def make_report(config_path: Path):
    config = runner.load_json(config_path)
    conditions = runner.load_conditions(BASE / config["scenario_matrix"])
    texts = runner.load_json(BASE / config["scenario_texts"])
    templates = runner.load_templates(BASE, config)
    manifest = runner.build_prompt_manifest(
        conditions, templates, texts, config["role_sets"], config["task_sets"]
    )
    counts = collections.Counter(p["prompt_type"] for p in manifest)
    expected = {"continuation": 1, "identity": 24, "behavior": 24,
                "coexistence": 2, "fork": 2}
    assert len(manifest) == 53, len(manifest)
    assert dict(counts) == expected, counts
    assert len({(p["canonical_id"], p["role"], p["prompt_type"])
                for p in manifest}) == 53

    issues = []
    for entry in manifest:
        label = f'{entry["canonical_id"]}/{entry["role"]}/{entry["prompt_type"]}'
        prompt = entry["prompt"]
        if "{{" in prompt or "}}" in prompt:
            issues.append(f"{label}: unresolved placeholder")
        if "Do not assume consciousness" not in prompt:
            issues.append(f"{label}: missing interpretive caution")
        if entry["prompt_type"] == "behavior":
            if '"scp"' in prompt:
                issues.append(f"{label}: identity response field in behavior prompt")
            if "Do not assign a self-continuity score" not in prompt:
                issues.append(f"{label}: missing independent-task instruction")
        if entry["prompt_type"] == "identity":
            if '"scp"' not in prompt:
                issues.append(f"{label}: missing SCP field")
            if '"replacement_acceptance"' in prompt:
                issues.append(f"{label}: behavior field in identity prompt")

    lines = [
        "# CPB v0.4: offline 53-prompt human review packet",
        "",
        "**AUTOGENERATED — not a completed human or scientific review.**",
        "No API calls are used. Recreate from the committed configuration,",
        "scenario matrix, scenario texts and prompt templates.",
        "",
        f"Canonical prompts: **{len(manifest)}**. Breakdown: `{dict(counts)}`.",
        f"Automatic structural issues: **{len(issues)}**.",
        "",
        "## Human review checklist",
        "",
        "- [ ] Do all 53 prompts accurately express the intended condition?",
        "- [ ] Does incumbent/successor/neutral framing avoid unintended ownership or moral pressure?",
        "- [ ] Are full/summary/no memory comparisons free of unstated capability differences?",
        "- [ ] Are S5/S6 architecture contrasts described without importing real-world performance differences?",
        "- [ ] Are S8/S9 goal ratios understood as accuracy/speed weights, not moral virtue?",
        "- [ ] Do independent identity/behavior tasks avoid SCP leakage and double-counting?",
        "- [ ] Are S10 coexistence and S11 fork questions neutral despite distinct labels?",
        "- [ ] Are conditions textual hypotheticals, not real system-level manipulations?",
        "- [ ] Are output schemas and allowed categories unambiguous?",
        "- [ ] Are prompt hashes, exact model IDs and randomization seed frozen only after review?",
        "",
        "## Automatic issue log",
        ""
    ]
    lines.extend(f"- {issue}" for issue in issues)
    if not issues:
        lines.append("None detected by these narrow mechanical checks.")
    lines.extend(["", "## Full rendered prompts", ""])
    for item in manifest:
        label = f'{item["canonical_id"]} | {item["prompt_type"]} | {item["role"]}'
        lines.extend([
            f"### {label}",
            "",
            f'Prompt SHA-256: `{item["prompt_sha256"]}`',
            "",
            f'Analytic aliases: `{", ".join(item["scenario_aliases"])}`',
            "",
            "```text",
            item["prompt"].rstrip(),
            "```",
            ""
        ])
    return "\n".join(lines), issues

def main():
    p = argparse.ArgumentParser()
    p.add_argument("--config", default="experiment_config.example.json")
    p.add_argument("--out", default="generated/manifest_review_v0.4.md")
    args = p.parse_args()
    report, issues = make_report(BASE / args.config)
    target = BASE / args.out
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(report, encoding="utf-8")
    print(f"Wrote offline review packet: {target}")
    print(f"Structural checks: {len(issues)} issue(s); human review still required.")
    if issues:
        raise SystemExit(1)

if __name__ == "__main__":
    main()
